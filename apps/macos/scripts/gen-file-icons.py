#!/usr/bin/env python3
"""Writes Sources/VornUI/FileIcons.swift and Resources/seti.ttf from the renderer's file-icons.tsx and seti.woff."""

import pathlib
import re
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = ROOT.parent.parent
TSX = REPO / "packages/web/src/renderer/components/file-icons.tsx"
WOFF = REPO / "packages/web/src/renderer/assets/seti.woff"
OUT = ROOT / "Sources/VornUI/FileIcons.swift"
TTF = ROOT / "Sources/VornUI/Resources/seti.ttf"


def woff_to_sfnt(data: bytes) -> bytes:
    flavor, _length, num_tables = struct.unpack(">4xIIH", data[:14])
    entries = []
    for i in range(num_tables):
        tag, offset, comp, orig, checksum = struct.unpack(">4sIIII", data[44 + i * 20 : 64 + i * 20])
        raw = data[offset : offset + comp]
        entries.append((tag, checksum, raw if comp == orig else zlib.decompress(raw)))
    search = 1
    shift = 0
    while search * 2 <= num_tables:
        search *= 2
        shift += 1
    header = struct.pack(">IHHHH", flavor, num_tables, search * 16, shift, num_tables * 16 - search * 16)
    offset = 12 + 16 * num_tables
    directory = b""
    body = b""
    for tag, checksum, table in entries:
        directory += struct.pack(">4sIII", tag, checksum, offset + len(body), len(table))
        body += table + b"\0" * ((4 - len(table) % 4) % 4)
    return header + directory + body


def literal(src: str, name: str) -> str:
    start = src.index(f"const {name}")
    open_brace = src.index("{", src.index("=", start))
    depth = 0
    for i in range(open_brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[open_brace + 1 : i]
    raise ValueError(name)


def key(k: str) -> str:
    return k.strip().strip("'\"")


def swift_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    src = TSX.read_text()
    defs = re.findall(r"^\s*('?[^:\n]+'?):\s*\{\s*ch:\s*'\\u([0-9A-Fa-f]{4})',\s*color:\s*'(#[0-9a-fA-F]{6})'\s*\}", literal(src, "D"), re.M)
    maps = {}
    for name in ("EXT", "LANG_EXT", "NAMES"):
        maps[name] = re.findall(r"^\s*('?[^:\n]+'?):\s*'([^']+)'", literal(src, name), re.M)
    lines = [
        "// Generated by scripts/gen-file-icons.py from packages/web/src/renderer/components/file-icons.tsx (Seti, MIT). Do not edit.",
        "",
        "enum FileIconTables {",
        "    static let defs: [String: (ch: UInt32, color: UInt32)] = [",
    ]
    lines += [f"        {swift_str(key(k))}: (0x{ch.upper()}, 0x{color[1:].upper()})," for k, ch, color in defs]
    lines.append("    ]")
    for name, swift in (("EXT", "ext"), ("LANG_EXT", "langExt"), ("NAMES", "names")):
        lines.append(f"    static let {swift}: [String: String] = [")
        seen = set()
        for k, v in maps[name]:
            if key(k) in seen:
                continue
            seen.add(key(k))
            lines.append(f"        {swift_str(key(k))}: {swift_str(v)},")
        lines.append("    ]")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    TTF.write_bytes(woff_to_sfnt(WOFF.read_bytes()))
    print(f"wrote {OUT} ({len(defs)} icons) and {TTF}")


if __name__ == "__main__":
    main()
