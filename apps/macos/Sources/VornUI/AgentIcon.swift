/// The mark for each agent a task can be assigned to, from AgentIcon.tsx.
public struct AgentIcon: View {
    let agent: AgentKind?
    let size: CGFloat

    /// `nil` draws the shell glyph, as the renderer does for anything it has no mark for.
    public init(_ agent: AgentKind?, size: CGFloat = 16) {
        self.agent = agent
        self.size = size
    }

    public var body: some View {
        Group {
            switch agent {
            case .claude:
                shape(Marks.claude).fill(Color(hex: 0xD97757))
            case .copilot:
                shape(Marks.copilot).fill(Color.white, style: FillStyle(eoFill: true))
            case .codex:
                ZStack {
                    shape(Marks.codexTile).fill(Color.white)
                    shape(Marks.codexGlyph).fill(gradient(
                        [(0xB1A7FF, 1, 0), (0x7A9DFF, 1, 0.5), (0x3941FF, 1, 1)], from: (12, 3), to: (12, 21)))
                }
            case .opencode:
                shape(Marks.opencode).fill(Color.white, style: FillStyle(eoFill: true))
            case .gemini:
                ZStack {
                    shape(Marks.gemini).fill(Color(hex: 0x3186FF))
                    shape(Marks.gemini).fill(gradient([(0x08B962, 1, 0), (0x08B962, 0, 1)], from: (7, 15.5), to: (11, 12)))
                    shape(Marks.gemini).fill(gradient([(0xF94543, 1, 0), (0xF94543, 0, 1)], from: (8, 5.5), to: (11.5, 11)))
                    shape(Marks.gemini).fill(gradient([(0xFABC12, 1, 0), (0xFABC12, 0, 0.46)], from: (3.5, 13.5), to: (17.5, 12)))
                }
            case nil:
                LucideIcon(.terminal, size: size, strokeWidth: 1.5).foregroundStyle(Theme.gray400)
            }
        }
        .frame(width: size, height: size)
    }

    private func shape(_ d: String) -> Path {
        let s = size / 24
        return Marks.path(d).applying(CGAffineTransform(scaleX: s, y: s))
    }

    /// A user-space SVG gradient over the 24-unit box.
    private func gradient(_ stops: [(UInt32, Double, CGFloat)], from: (CGFloat, CGFloat), to: (CGFloat, CGFloat)) -> LinearGradient {
        LinearGradient(
            stops: stops.map { .init(color: Color(hex: $0.0).opacity($0.1), location: $0.2) },
            startPoint: UnitPoint(x: from.0 / 24, y: from.1 / 24),
            endPoint: UnitPoint(x: to.0 / 24, y: to.1 / 24)
        )
    }
}

